// Type definitions for Mural Generator

export interface ReferenceMural {
  id: string;
  collectionName: string;
  designName: string;
  colorVariant: string | null;
  localFilePath: string;
  fileName: string;
  metadata: string | null;
  importedAt: Date;
  // Artistic description fields
  artisticDescription: string | null;
  descriptionGeneratedAt: Date | null;
  descriptionBatchJobId: string | null;
}

export interface GeneratedMural {
  id: string;
  referenceMuralId: string;
  prompt: string;
  isCustomPrompt: boolean;
  localFilePath: string;
  fileName: string;
  modelUsed: string | null;
  generationParams: string | null;
  createdAt: Date;
}

export interface GenerationRequest {
  referenceMuralId: string;
  prompt: string;
  isCustomPrompt: boolean;
}

export interface PromptAnalysisResult {
  suggestedPrompt: string;
  styleElements: {
    subjects?: string[];
    technique?: string;
    colorPalette?: string[];
    composition?: string;
  };
}

/**
 * Artistic description structure for murals
 * Generated by batch AI analysis following a specific JSON schema
 */
export interface ArtisticDescription {
  text_message: string;
  json_prompt: {
    meta_tags: {
      style_category: string;
      seamless_potential: boolean;
      perspective_type: string;
    };
    artistic_reference: {
      art_movement: string;
      influential_artists: string[];
      era: string;
    };
    medium_and_texture: {
      primary_medium: string;
      background_substrate: string;
      brushwork_style: string;
    };
    visual_composition: {
      subject_matter: string;
      structural_layout: string;
      key_elements: string[];
    };
    color_profile: {
      dominant_palette: string;
      mood: string;
      lighting: string;
    };
  };
}

/**
 * Batch job tracking for description generation
 */
export interface BatchDescriptionJob {
  jobId: string;
  status: 'pending' | 'processing' | 'completed' | 'failed';
  totalMurals: number;
  processedMurals?: number;
  succeededMurals?: number;
  failedMurals?: number;
  createdAt: Date;
  completedAt?: Date;
}

/**
 * Conflict resolution strategies for batch job creation
 */
export type BatchConflictStrategy =
  | 'SKIP_CONFLICTS'      // Only create jobs for murals without existing jobs
  | 'RETRY_FAILED'        // Keep PENDING/RUNNING/SUCCEEDED, replace FAILED/EXPIRED/CANCELLED
  | 'REPLACE_ALL';        // Delete all existing jobs and create new ones

/**
 * Conflict detection result for a single mural
 */
export interface MuralConflict {
  muralId: string;
  collectionName: string;
  designName: string;
  colorVariant: string | null;
  existingJob: {
    id: string;
    batchJobId: string;
    status: string;
    submittedAt: Date;
    completedAt: Date | null;
    errorMessage: string | null;
  } | null;
}

/**
 * Conflict summary for batch operation
 */
export interface BatchConflictSummary {
  totalMurals: number;
  conflicts: {
    pending: number;
    running: number;
    succeeded: number;
    failed: number;
    expired: number;
    cancelled: number;
  };
  murals: MuralConflict[];
}

/**
 * Resolution preview for a strategy
 */
export interface BatchResolutionPreview {
  strategy: BatchConflictStrategy;
  willCreate: number;
  willSkip: number;
  willArchive: number;
  warnings: string[];
}
